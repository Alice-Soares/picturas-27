  VIDEO_FRAME_EXTRACT_DESTINATION_NOT_FOUND: "VIDEO_FRAME_EXTRACT_DESTINATION_NOT_FOUND",
  VIDEO_FRAME_EXTRACT_INVALID_PARAMETERS: "VIDEO_FRAME_EXTRACT_INVALID_PARAMETERS",
  VIDEO_FRAME_EXTRACT_INVALID_VIDEO: "VIDEO_FRAME_EXTRACT_INVALID_VIDEO",
  VIDEO_FRAME_EXTRACT_INVALID_INTERVAL: "VIDEO_FRAME_EXTRACT_INVALID_INTERVAL",
  VIDEO_FRAME_EXTRACT_INVALID_MAX_FRAMES: "VIDEO_FRAME_EXTRACT_INVALID_MAX_FRAMES",
  VIDEO_FRAME_EXTRACT_NO_FRAMES: "VIDEO_FRAME_EXTRACT_NO_FRAMES",
