function publicFrameExtractionError(error) {
  const code = errorMessages[error?.message] || errorMessages[error?.code];
  return {
    code: code || errorMessages.VIDEO_FRAME_EXTRACT_FAILED,
    message: code || errorMessages.VIDEO_FRAME_EXTRACT_FAILED,
  };
}

module.exports = { publicFrameExtractionError };